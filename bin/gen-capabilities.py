#!/usr/bin/env python3
"""gen-capabilities.py — derive memory/capabilities.md from a Core's LIVE config.

WHY: capabilities.md ("what this Core does") rotted into an untouched template in
business + school because nothing maintained it. Hand-maintained self-knowledge
rots; derived-from-truth can't. This regenerates the FACTUAL inventory block from
the Core's own wiring at every close, so each Core's "what it does" is always
current — and per-Core BY CONSTRUCTION (it reads each Core's own config, so
finance shows its bots, school its canvas automation, etc.: "memory format from
actual data + workflow").

WHAT IT MANAGES: a single delimited block between
  <!-- CAPABILITIES:AUTO --> ... <!-- /CAPABILITIES:AUTO -->
Everything OUTSIDE that block (the hand-written ## Notes — outward-action posture,
privacy nuance, bot $-caps) is preserved untouched. Idempotent.

SCANS (all best-effort, fail-open): .claude/settings.json hooks · .claude/commands
· .claude/agents · .claude/skills · .mcp.json mcpServers · settings.json
enabledPlugins · ~/Library/LaunchAgents/<identity.launchagent_label_prefix>.*

Shared baseline file (bin/). Per-Core via .claude/identity.json. No args needed;
honors $CORE_INSTANCE, else git toplevel, else cwd.
"""
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

BEGIN = "<!-- CAPABILITIES:AUTO — generated by bin/gen-capabilities.py; do not edit inside this block -->"
END = "<!-- /CAPABILITIES:AUTO -->"


def _root() -> Path:
    r = os.environ.get("CORE_INSTANCE")
    if r:
        return Path(r)
    try:
        out = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, timeout=5)
        if out.returncode == 0 and out.stdout.strip():
            return Path(out.stdout.strip())
    except Exception:
        pass
    return Path.cwd()


def _load_json(p: Path):
    try:
        return json.loads(p.read_text())
    except Exception:
        return {}


def _names(globpat, root: Path, strip_suffix=".md"):
    try:
        out = []
        for f in sorted(root.glob(globpat)):
            n = f.name
            if strip_suffix and n.endswith(strip_suffix):
                n = n[: -len(strip_suffix)]
            out.append(n)
        return out
    except Exception:
        return []


def _hooks(settings: dict):
    """event -> sorted unique hook-script basenames."""
    res = {}
    for ev, groups in (settings.get("hooks") or {}).items():
        seen = []
        for grp in groups or []:
            for h in grp.get("hooks", []) or []:
                cmd = h.get("command", "")
                m = re.search(r"([\w.-]+\.(?:sh|py))", cmd)
                if m and m.group(1) not in seen:
                    seen.append(m.group(1))
        if seen:
            res[ev] = sorted(seen)
    return res


def _skills(root: Path):
    out = []
    sk = root / ".claude" / "skills"
    if sk.is_dir():
        for d in sorted(sk.iterdir()):
            if (d / "SKILL.md").is_file():
                out.append(d.name)
    return out


def _launchd(prefix: str):
    if not prefix:
        return []
    la = Path.home() / "Library" / "LaunchAgents"
    try:
        return sorted(p.name[: -len(".plist")] for p in la.glob(f"{prefix}.*.plist"))
    except Exception:
        return []


def _from_manifests(root: Path):
    """Prefer the discovery-engine manifests (bin/gen-core-manifest.py) — they see
    user-scope PLUGINS (commands/skills/agents/hooks) that the legacy live scan
    below misses. Returns a dict of rendered inputs, or None if manifests absent."""
    core = _load_json(root / "memory" / "core-manifest.json")
    host = _load_json(root / "memory" / "host-manifest.json")
    if not core or not core.get("inventory"):
        return None
    ci = core["inventory"]
    hi = (host or {}).get("inventory", {})

    # Hooks: event -> [names], merging core + host(plugin) hooks.
    hooks = {}
    for h in ci.get("hooks", []) + hi.get("hooks", []):
        hooks.setdefault(h["event"], [])
        label = h["name"] + (f" ({h['source']})" if h.get("source", "").startswith("plugin:") else "")
        if label not in hooks[h["event"]]:
            hooks[h["event"]].append(label)
    for ev in hooks:
        hooks[ev].sort()

    def names(items):
        return [i["name"] for i in items]

    return {
        "hooks": hooks,
        "commands": sorted(names(ci.get("commands", [])) + names(hi.get("commands", []))),
        "agents": sorted(names(ci.get("agents", [])) + names(hi.get("agents", []))),
        "skills": sorted(set(names(ci.get("skills", [])) + names(hi.get("skills", [])))),
        "servers": sorted(set(names(ci.get("mcp", [])) + names(hi.get("mcp", [])))),
        "plugins": sorted(f"{p['name']}" + ("" if p.get("enabled") else " (disabled)")
                          for p in hi.get("plugins", [])),
        "jobs": names(ci.get("daemons", [])),
    }


def build_block(root: Path) -> str:
    identity = _load_json(root / ".claude" / "identity.json")
    # Fallback domain to the dir name (core-finance -> finance) so a missing/partial
    # identity.json never yields a "?" Core — robustness over a known gap.
    domain = identity.get("domain_label") or re.sub(r"^core-", "", root.name) or "?"

    src = _from_manifests(root)
    if src is not None:
        hooks = src["hooks"]
        commands, agents, skills = src["commands"], src["agents"], src["skills"]
        servers, plugins, jobs = src["servers"], src["plugins"], src["jobs"]
    else:
        # Legacy fallback — live scan (misses user-scope plugins; kept for robustness
        # when the manifest hasn't been generated yet on a fresh clone).
        settings = _load_json(root / ".claude" / "settings.json")
        mcp = _load_json(root / ".mcp.json")
        prefix = identity.get("launchagent_label_prefix", "")
        hooks = _hooks(settings)
        commands = _names(".claude/commands/*.md", root)
        agents = _names(".claude/agents/*.md", root)
        skills = _skills(root)
        servers = sorted((mcp.get("mcpServers") or {}).keys())
        plugins = sorted(k for k, v in (settings.get("enabledPlugins") or {}).items() if v)
        jobs = _launchd(prefix)

    now = os.environ.get("GEN_CAPABILITIES_DATE") or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    L = [BEGIN,
         f"## Inventory — what this `{domain}` Core does (auto-derived {now})",
         "*Generated from live config by `bin/gen-capabilities.py`. Do not hand-edit inside this block — edits are overwritten at session close. Add context in `## Notes` below.*",
         ""]

    def section(title, items, fmt=lambda x: f"`{x}`"):
        L.append(f"### {title} ({len(items)})")
        if items:
            L.append(", ".join(fmt(i) for i in items))
        else:
            L.append("_none_")
        L.append("")

    L.append(f"### Hooks ({sum(len(v) for v in hooks.values())} across {len(hooks)} events)")
    if hooks:
        # EVERY registered event, not a hardcoded six. The list used to be
        # ["SessionStart","UserPromptSubmit","PreToolUse","PostToolUse","Stop","SessionEnd"] while the
        # header one line above counted len(hooks) — so this file claimed more events than it listed and
        # silently omitted every hook on any other event. reply-observer.py has been registered on
        # MessageDisplay since 2026-08-06 and does not appear anywhere in the generated inventory;
        # close-reconciler noticed the absence and correctly guessed a generator gap rather than an
        # author error. settings.json currently registers ~17 events.
        #
        # The named order is kept as a PREFERENCE for stable, readable output, then anything else is
        # appended — so a new event type is never dropped again, only sorted late.
        _ORDER = ["SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "PostToolBatch",
                  "MessageDisplay", "Stop", "SubagentStop", "PreCompact", "SessionEnd"]
        # key=str because the keys are not guaranteed to be strings. sentinel-code traced it: the
        # settings.json path can only ever produce str keys (JSON object keys always are), but
        # _from_manifests() does `hooks.setdefault(h["event"], [])` straight from a local manifest with
        # no type check, so a null or numeric "event" becomes a non-string key. The OLD code only
        # `in`-checked six literals and never sorted, so this was inert; sorting a mix of str and None
        # raises TypeError, and render() is not wrapped — it would CRASH the close on every Core rather
        # than fail open, which is the opposite of this file's stated design. Sorting by str() keeps the
        # keys themselves intact for the hooks[ev] lookup below.
        for ev in _ORDER + sorted((e for e in hooks if e not in _ORDER), key=str):
            if ev in hooks:
                L.append(f"- **{ev}:** " + ", ".join(f"`{h}`" for h in hooks[ev]))
    else:
        L.append("_none_")
    L.append("")

    section("Slash commands", commands)
    section("Agents", agents)
    section("Skills", skills)
    section("MCP servers", servers)
    section("Plugins", plugins)
    section("Daemons / launchd", jobs)

    L.append(END)
    return "\n".join(L)


TEMPLATE_MARKERS = ("Populated by you as you wire things on", "(list as you add them)")


def render(root: Path) -> str:
    block = build_block(root)
    cap = root / "memory" / "capabilities.md"
    existing = ""
    try:
        existing = cap.read_text()
    except Exception:
        pass

    # Idempotent: if the managed block already exists, replace it in place.
    if BEGIN in existing and END in existing:
        pre = existing.split(BEGIN, 1)[0]
        post = existing.split(END, 1)[1]
        return pre.rstrip() + "\n\n" + block + "\n" + post.lstrip("\n")

    # First run on an untouched template → clean file (template body is junk).
    if existing and any(m in existing for m in TEMPLATE_MARKERS):
        return ("# Active capabilities\n\n"
                "What this Core can do — the factual inventory is auto-derived from live config; "
                "hand-written context lives under `## Notes`.\n\n"
                f"{block}\n\n## Notes\n_(hand-written context — outward-action posture, "
                "privacy nuance, bot caps, data-flow specifics. Preserved across regeneration.)_\n")

    # First run on a file with REAL hand-written content → insert block after the
    # first heading, preserve everything else verbatim (becomes the Notes body).
    if existing.strip():
        lines = existing.splitlines()
        head_idx = next((i for i, ln in enumerate(lines) if ln.startswith("# ")), -1)
        if head_idx >= 0:
            head = "\n".join(lines[: head_idx + 1])
            rest = "\n".join(lines[head_idx + 1:]).lstrip("\n")
            return f"{head}\n\n{block}\n\n## Notes (preserved)\n\n{rest}\n"
        return f"{block}\n\n## Notes (preserved)\n\n{existing}\n"

    # No file at all.
    return ("# Active capabilities\n\n"
            f"{block}\n\n## Notes\n_(hand-written context. Preserved across regeneration.)_\n")


def main():
    root = _root()
    cap = root / "memory" / "capabilities.md"
    new = render(root)
    if "--check" in sys.argv or "--dry-run" in sys.argv:
        old = ""
        try:
            old = cap.read_text()
        except Exception:
            pass
        changed = (old != new)
        print(f"[gen-capabilities] {root.name}: {'WOULD CHANGE' if changed else 'current'}")
        sys.exit(10 if changed else 0)
    try:
        cap.parent.mkdir(parents=True, exist_ok=True)
        cap.write_text(new)
        print(f"[gen-capabilities] {root.name}: capabilities.md regenerated from live config")
    except Exception as e:
        print(f"[gen-capabilities] WARN: could not write capabilities.md: {e}", file=sys.stderr)
        sys.exit(0)  # fail-open — never block a close


if __name__ == "__main__":
    main()
